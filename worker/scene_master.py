"""FFmpeg scene-master assembly. No remote fetches, GPU use or provider billing."""
import json
import subprocess
from pathlib import Path

RATIOS = {
    '16:9': '1280:720', '9:16': '720:1280',
    '1:1': '720:720', '4:5': '720:900', '2.39:1': '1280:536',
}
MAX_SCENES = 8
MAX_SONG_SECONDS = 600
MAX_CLIP_SECONDS = 30


def inspect_media(source):
    data = json.loads(subprocess.check_output([
        'ffprobe', '-v', 'error', '-show_entries',
        'format=duration:stream=codec_type,codec_name',
        '-of', 'json', str(source),
    ], text=True, timeout=30))
    seconds = float(data.get('format', {}).get('duration') or 0)
    return seconds, {s.get('codec_type') for s in data.get('streams', [])}


def assemble_scene_master(audio, scene_paths, output, outdir, ratio):
    """Generate an H264/AAC MP4 from genuine uploaded video frames and audio.

    Scenes are transcoded to consistent geometry/timebase, looped in sequence
    until the song ends, and muxed with the supplied soundtrack. Neither stills
    nor blank placeholders are created. All sources must be in the job folder.
    """
    if ratio not in RATIOS:
        raise ValueError('Invalid output ratio')
    if not 1 <= len(scene_paths) <= MAX_SCENES:
        raise ValueError('Provide between 1 and 8 real video scenes')
    job_dir = Path(audio).resolve().parent
    audio_seconds, audio_streams = inspect_media(audio)
    if 'audio' not in audio_streams or not 0 < audio_seconds <= MAX_SONG_SECONDS:
        raise ValueError('Soundtrack must be decodable and 10 minutes or less')

    width, height = RATIOS[ratio].split(':')
    normalized = []
    for number, entry in enumerate(scene_paths):
        original = Path(entry).resolve()
        if original.parent != job_dir or not original.is_file():
            raise ValueError('Scene source must be a local file in its own job folder')
        duration, streams = inspect_media(original)
        if 'video' not in streams or duration < 0.15:
            raise ValueError('Scene source has no usable moving video frames')

        target = Path(outdir) / f'normalized_{number:02d}.mp4'
        vf = (
            f'scale={width}:{height}:force_original_aspect_ratio=decrease,'
            f'pad={width}:{height}:(ow-iw)/2:(oh-ih)/2,'
            'fps=30,setsar=1,format=yuv420p'
        )
        subprocess.run([
            'ffmpeg', '-nostdin', '-hide_banner', '-loglevel', 'error', '-y',
            '-i', str(original), '-t', str(MAX_CLIP_SECONDS), '-an',
            '-vf', vf, '-c:v', 'libx264', '-preset', 'veryfast',
            '-pix_fmt', 'yuv420p', str(target),
        ], check=True, timeout=300, capture_output=True, text=True)
        normalized.append(target)

    playlist = Path(outdir) / 'scene_playlist.txt'
    # Known filenames generated by this function; no user-controlled text.
    playlist.write_text(''.join(f"file '{p.name}'\\n" for p in normalized), encoding='utf-8')
    subprocess.run([
        'ffmpeg', '-nostdin', '-hide_banner', '-loglevel', 'error', '-y',
        '-stream_loop', '-1', '-f', 'concat', '-safe', '0', '-i', str(playlist),
        '-i', str(audio), '-t', f'{audio_seconds:.3f}',
        '-map', '0:v:0', '-map', '1:a:0',
        '-c:v', 'copy', '-c:a', 'aac', '-b:a', '192k',
        '-movflags', '+faststart', str(output),
    ], check=True, timeout=600, capture_output=True, text=True)
    return {'mode': 'scene-master', 'sceneCount': len(normalized),
            'soundtrackSeconds': round(audio_seconds, 3)}
